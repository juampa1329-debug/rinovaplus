CREATE TABLE dbo.CRMMasivoPlantilla (
 InstitutionId uniqueidentifier NOT NULL,
 TemplateId uniqueidentifier NOT NULL,
 VersionNo int NOT NULL,
 IntegrationId uniqueidentifier NOT NULL,
 ProviderId varchar(200) NOT NULL,
 Name varchar(128) NOT NULL,
 Language varchar(20) NOT NULL,
 Category varchar(40) NOT NULL,
 ProviderStatus varchar(40) NOT NULL,
 Origin varchar(16) NOT NULL,
 Paused bit NOT NULL,
 Definition nvarchar(max) NOT NULL,
 ProviderMetadata nvarchar(max) NOT NULL,
 AccountVersion binary(8) NOT NULL,
 CredentialId uniqueidentifier NULL,
 ObservedAt datetime2(7) NOT NULL,
 CONSTRAINT PK_P7Plantilla PRIMARY KEY(InstitutionId,TemplateId,VersionNo),
 CONSTRAINT UQ_P7Plantilla UNIQUE(InstitutionId,IntegrationId,ProviderId,VersionNo),
 CONSTRAINT FK_P7PlantillaCuenta FOREIGN KEY(InstitutionId,IntegrationId) REFERENCES dbo.CRMCanalInstitucionalIntegracion(InstitutionId,IntegrationId),
 CONSTRAINT CK_P7Plantilla CHECK(VersionNo>0 AND ISJSON(Definition)=1 AND ISJSON(ProviderMetadata)=1 AND Origin IN('provider','controlled','operator'))
);
CREATE TABLE dbo.CRMMasivoCampana (
 InstitutionId uniqueidentifier NOT NULL,
 CampaignId uniqueidentifier NOT NULL,
 Name nvarchar(160) NOT NULL,
 IntegrationId uniqueidentifier NOT NULL,
 TemplateId uniqueidentifier NOT NULL,
 TemplateVersion int NOT NULL,
 Document nvarchar(max) NOT NULL,
 State varchar(16) NOT NULL,
 Revision int NOT NULL,
 Epoch int NOT NULL,
 ScheduledAt datetime2(7) NULL,
 Timezone varchar(80) NOT NULL,
 ActorId uniqueidentifier NULL,
 ActorAuthVersion int NULL,
 ActorSessionId uniqueidentifier NULL,
 ApprovedAt datetime2(7) NULL,
 CreatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7CampanaInicio DEFAULT SYSUTCDATETIME(),
 UpdatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7CampanaFecha DEFAULT SYSUTCDATETIME(),
 RowVersion rowversion NOT NULL,
 CONSTRAINT PK_P7Campana PRIMARY KEY(InstitutionId,CampaignId),
 CONSTRAINT FK_P7CampanaCuenta FOREIGN KEY(InstitutionId,IntegrationId) REFERENCES dbo.CRMCanalInstitucionalIntegracion(InstitutionId,IntegrationId),
 CONSTRAINT FK_P7CampanaPlantilla FOREIGN KEY(InstitutionId,TemplateId,TemplateVersion) REFERENCES dbo.CRMMasivoPlantilla(InstitutionId,TemplateId,VersionNo),
 CONSTRAINT FK_P7CampanaActor FOREIGN KEY(InstitutionId,ActorId) REFERENCES dbo.CRMAccesoUsuario(InstitutionId,UserId),
 CONSTRAINT FK_P7CampanaSesion FOREIGN KEY(InstitutionId,ActorSessionId) REFERENCES dbo.CRMAccesoSesion(InstitutionId,SessionId),
 CONSTRAINT CK_P7Campana CHECK(Revision>0 AND Epoch>0 AND ISJSON(Document)=1 AND State IN('draft','scheduled','running','paused','cancelled','completed'))
);
CREATE TABLE dbo.CRMMasivoConsentimiento (
 InstitutionId uniqueidentifier NOT NULL,
 ConsentId uniqueidentifier NOT NULL,
 IntegrationId uniqueidentifier NOT NULL,
 IdentityId uniqueidentifier NOT NULL,
 VersionNo int NOT NULL,
 State varchar(12) NOT NULL,
 Evidence nvarchar(1000) NOT NULL,
 Origin nvarchar(200) NOT NULL,
 ExpiresAt datetime2(7) NULL,
 ActorId uniqueidentifier NOT NULL,
 OperationId uniqueidentifier NOT NULL,
 CreatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7ConsentimientoFecha DEFAULT SYSUTCDATETIME(),
 CONSTRAINT PK_P7Consentimiento PRIMARY KEY(InstitutionId,ConsentId),
 CONSTRAINT UQ_P7Consentimiento UNIQUE(InstitutionId,IntegrationId,IdentityId,VersionNo),
 CONSTRAINT FK_P7ConsentimientoIdentidad FOREIGN KEY(InstitutionId,IdentityId) REFERENCES dbo.CRMCanalInstitucionalIdentidadExterna(InstitutionId,IdentityId),
 CONSTRAINT FK_P7ConsentimientoCuenta FOREIGN KEY(InstitutionId,IntegrationId) REFERENCES dbo.CRMCanalInstitucionalIntegracion(InstitutionId,IntegrationId),
 CONSTRAINT FK_P7ConsentimientoActor FOREIGN KEY(InstitutionId,ActorId) REFERENCES dbo.CRMAccesoUsuario(InstitutionId,UserId),
 CONSTRAINT CK_P7Consentimiento CHECK(VersionNo>0 AND State IN('granted','revoked') AND LEN(Evidence)>0 AND LEN(Origin)>0 AND (State<>'granted' OR ExpiresAt IS NOT NULL AND ExpiresAt>CreatedAt))
);
CREATE TABLE dbo.CRMMasivoDestinatario (
 InstitutionId uniqueidentifier NOT NULL,
 RecipientId uniqueidentifier NOT NULL,
 CampaignId uniqueidentifier NOT NULL,
 IdentityId uniqueidentifier NOT NULL,
 ContactId uniqueidentifier NOT NULL,
 ConversationId uniqueidentifier NOT NULL,
 CampaignRevision int NOT NULL,
 CampaignEpoch int NOT NULL,
 ConsentId uniqueidentifier NOT NULL,
 ConsentVersion int NOT NULL,
 ControlEpoch bigint NOT NULL,
 AccountVersion binary(8) NOT NULL,
 State varchar(16) NOT NULL,
 Snapshot nvarchar(max) NOT NULL,
 CurrentQueueId uniqueidentifier NULL,
 Attempts int NOT NULL CONSTRAINT DF_P7DestinatarioIntentos DEFAULT 0,
 LastError varchar(80) NULL,
 CreatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7DestinatarioInicio DEFAULT SYSUTCDATETIME(),
 UpdatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7DestinatarioFecha DEFAULT SYSUTCDATETIME(),
 CONSTRAINT PK_P7Destinatario PRIMARY KEY(InstitutionId,RecipientId),
 CONSTRAINT UQ_P7Destinatario UNIQUE(InstitutionId,CampaignId,IdentityId),
 CONSTRAINT FK_P7DestinatarioCampana FOREIGN KEY(InstitutionId,CampaignId) REFERENCES dbo.CRMMasivoCampana(InstitutionId,CampaignId),
 CONSTRAINT FK_P7DestinatarioIdentidad FOREIGN KEY(InstitutionId,IdentityId) REFERENCES dbo.CRMCanalInstitucionalIdentidadExterna(InstitutionId,IdentityId),
 CONSTRAINT FK_P7DestinatarioContacto FOREIGN KEY(ContactId) REFERENCES dbo.CRMContacto(ContactId),
 CONSTRAINT FK_P7DestinatarioConversacion FOREIGN KEY(ConversationId) REFERENCES dbo.CRMConversacion(ConversationId),
 CONSTRAINT FK_P7DestinatarioConsentimiento FOREIGN KEY(InstitutionId,ConsentId) REFERENCES dbo.CRMMasivoConsentimiento(InstitutionId,ConsentId),
 CONSTRAINT FK_P7DestinatarioCola FOREIGN KEY(InstitutionId,CurrentQueueId) REFERENCES dbo.CRMCanalInstitucionalEnvioTrabajo(InstitutionId,QueueId),
 CONSTRAINT CK_P7Destinatario CHECK(State IN('prepared','queued','blocked','cancelled') AND Attempts BETWEEN 0 AND 20 AND CampaignRevision>0 AND CampaignEpoch>0 AND ConsentVersion>0 AND ISJSON(Snapshot)=1)
);
CREATE TABLE dbo.CRMMasivoIntento (
 InstitutionId uniqueidentifier NOT NULL,
 RecipientId uniqueidentifier NOT NULL,
 AttemptNo int NOT NULL,
 QueueId uniqueidentifier NOT NULL,
 OperationId uniqueidentifier NOT NULL,
 CreatedAt datetime2(7) NOT NULL CONSTRAINT DF_P7IntentoFecha DEFAULT SYSUTCDATETIME(),
 CONSTRAINT PK_P7Intento PRIMARY KEY(InstitutionId,RecipientId,AttemptNo),
 CONSTRAINT UQ_P7IntentoCola UNIQUE(InstitutionId,QueueId),
 CONSTRAINT FK_P7IntentoDestinatario FOREIGN KEY(InstitutionId,RecipientId) REFERENCES dbo.CRMMasivoDestinatario(InstitutionId,RecipientId),
 CONSTRAINT FK_P7IntentoCola FOREIGN KEY(InstitutionId,QueueId) REFERENCES dbo.CRMCanalInstitucionalEnvioTrabajo(InstitutionId,QueueId),
 CONSTRAINT CK_P7Intento CHECK(AttemptNo BETWEEN 1 AND 20)
);
CREATE TABLE dbo.CRMMasivoCadencia (
 InstitutionId uniqueidentifier NOT NULL,
 IntegrationId uniqueidentifier NOT NULL,
 Enabled bit NOT NULL,
 DailyLimit int NOT NULL,
 IntervalSeconds int NOT NULL,
 WindowAt datetime2(7) NOT NULL,
 Reserved int NOT NULL,
 NextAt datetime2(7) NOT NULL,
 Revision int NOT NULL,
 CONSTRAINT PK_P7Cadencia PRIMARY KEY(InstitutionId,IntegrationId),
 CONSTRAINT FK_P7CadenciaCuenta FOREIGN KEY(InstitutionId,IntegrationId) REFERENCES dbo.CRMCanalInstitucionalIntegracion(InstitutionId,IntegrationId),
 CONSTRAINT CK_P7Cadencia CHECK(DailyLimit BETWEEN 1 AND 100000 AND IntervalSeconds BETWEEN 1 AND 86400 AND Reserved>=0 AND Revision>0)
);
